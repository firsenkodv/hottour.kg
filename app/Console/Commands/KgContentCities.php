    public function handle(): int
    {
        $apply = (bool) $this->option('apply');
        $reportPath = base_path('temp/kg-cities-report.txt');
        $report = [];
        $totalRows = 0;
        $totalFields = 0;

        foreach (self::TABLES as $table) {
            $columns = $this->textColumns($table);
            if ($columns === []) {
                continue;
            }

            $query = DB::table($table)->where(function ($q) use ($columns) {
                $needles = [
                    'Алмат', 'Астан', 'азахстан', 'hottour.kz',
                    'Тараз', 'Шымкент', 'Актау', 'Актобе', 'Атырау',
                    'Караганд', 'Павлодар', 'Усть-Каменогорск',
                ];
                foreach ($columns as $c) {
                    foreach ($needles as $needle) {
                        $q->orWhere($c, 'like', "%$needle%");
                    }
                }
            });

            if (isset(self::EXCLUDED_ROWS[$table])) {
                $query->whereNotIn('id', self::EXCLUDED_ROWS[$table]);
            }

            foreach ($query->orderBy('id')->get() as $row) {
                $changes = [];

                foreach ($columns as $column) {
                    $old = (string) ($row->{$column} ?? '');
                    if ($old === '') {
                        continue;
                    }

                    $new = $this->transform($old);
                    if ($new !== $old) {
                        $changes[$column] = $new;
                        $totalFields++;
                        $report[] = $this->diffLines($table, (int) $row->id, $column, $old);
                    }
                }

                if ($changes !== []) {
                    $totalRows++;
                    if ($apply) {
                        DB::table($table)->where('id', $row->id)->update($changes);
                    }
                }
            }
        }

        @mkdir(dirname($reportPath), 0777, true);
        file_put_contents($reportPath, implode("\n", array_merge(...$report ?: [[]])));

        $this->info(sprintf(
            '%s: строк %d, полей %d. Отчёт: %s',
            $apply ? 'ПРИМЕНЕНО' : 'Отчёт (без изменений, запустите с --apply)',
            $totalRows,
            $totalFields,
            $reportPath,
        ));

        $this->warn('Исключено из автозамены, требует ручной редактуры:');
        foreach (self::EXCLUDED_ROWS as $table => $ids) {
            foreach ($ids as $id) {
                $title = (string) DB::table($table)->where('id', $id)->value('title');
                $this->line("  $table #$id  $title");
            }
        }

        return self::SUCCESS;
    }

    /** @return list<string> */
    private function textColumns(string $table): array
    {
        $columns = [];
        foreach (DB::select("SHOW COLUMNS FROM `$table`") as $col) {
            if (preg_match('/char|text|json/i', $col->Type)
                && ! \in_array($col->Field, self::EXCLUDED_COLUMNS, true)) {
                $columns[] = $col->Field;
            }
        }

        return $columns;
    }

    private function transform(string $text): string
    {
        // спрятать «Эйр Астану» (дубль в скобках нормализуем сразу)
        $protected = [];
        $text = preg_replace_callback(self::PROTECT, function ($m) use (&$protected) {
            $token = "\u{27EA}" . \count($protected) . "\u{27EB}";
            $protected[$token] = preg_replace('/\s*\(Астан[а-яё]*\)/u', '', $m[0]);

            return $token;
        }, $text);

        foreach (self::PRE_CLEAN as [$pattern, $replacement]) {
            $text = preg_replace($pattern, $replacement, $text);
        }

        foreach (self::RULES as [$pattern, $replacement]) {
            $text = preg_replace($pattern, $replacement, $text);
        }

        return strtr($text, $protected);
    }

    /** @return list<string> */
    private function diffLines(string $table, int $id, string $column, string $old): array
    {
        $lines = ["## $table #$id  $column"];
        preg_match_all('/.{0,30}(Алмат[а-яё]*|Астан[а-яё]*|[Кк]азахстан[а-яё]*|АСТАН[А-ЯЁ]*|АЛМАТЫ|КАЗАХСТАН[А-ЯЁ]*|[Тт]араз[а-яё]*|[Шш]ымкент[а-яё]*|[Шш]ымкет[а-яё]*|Актау|Актобе|Атырау|Караганд[а-яё]*|Павлодар[а-яё]*|Усть-Каменогорск[а-яё]*|hottour\.kz).{0,30}/u', $old, $m);

        foreach (array_slice(array_unique($m[0]), 0, 6) as $fragment) {
            $fragment = preg_replace('/\s+/', ' ', $fragment);
            $lines[] = '  − ' . $fragment;
            $lines[] = '  + ' . preg_replace('/\s+/', ' ', $this->transform($fragment));
        }

        return $lines;
    }
}
