/**
 * Перевод текстов материалов с казахстанских городов на киргизские:
 * Алматы -> Бишкек, Астана -> Ош, Казахстан -> Кыргызстан.
 *
 * Замена выполняется ПО МЕСТУ в той базе, где запущена команда, — на проде
 * она преобразует продовые тексты со всеми их правками, ничего не затирая
 * локальными версиями. Дампы между окружениями не переносятся.
 *
 * Без флагов — только отчёт (dry-run): что и где будет заменено, с
 * фрагментами «до -> после» в temp/kg-cities-report.txt. С флагом --apply —
 * применяет изменения. Команда идемпотентна: после замены совпадений
 * не остаётся, повторный запуск ничего не делает.
 *
 * Что сознательно НЕ трогается:
 *  - колонки slug и латиница в ссылках (iz-almaty и т.п.) — смена URL
 *    обрушила бы внешние ссылки и SEO-индекс;
 *  - «Эйр Астана» / Air Astana — название авиакомпании;
 *  - tours и customer_hot_tours — это города вылета (механика поиска),
 *    а не тексты материалов; hotel_mains.city — тоже город вылета;
 *  - контакты — уже переведены миграцией 2026_08_17_100000;
 *  - EXCLUDED_ROWS — материалы, где замена дала бы ложную географию
 *    (казахстанские экскурсии, статья о визе в Киргизию). Их надо
 *    редактировать руками, команда перечисляет их в конце вывода.
 *
 * Склонения: «Алматы» не склоняется, поэтому падеж Бишкека берётся из
 * предлога («из Алматы» -> «из Бишкека»; «в Алматы» по фактическим текстам
 * везде местный падеж -> «в Бишкеке»; «рядом с Алматы» — творительный ->
 * «рядом с Бишкеком»). Формы Астаны и Казахстана меняются пословоформенно.
 * Все правила с границами слова: «рейс Алматы-Санья» не должен попадать
 * под правило «с Алматы».
 */
class KgContentCities extends Command
