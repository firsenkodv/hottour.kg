    /**
     * Название авиакомпании «Эйр Астана»: прячется в токен до замен,
     * возвращается после. Дубль в скобках «Эйр Астана (Астана)» —
     * мусор прошлых автозамен, нормализуется до названия без скобок.
     */
    private const PROTECT = '/Эйр\s+Астан[а-яё]*(?:\s*\(Астан[а-яё]*\))?|Air\s+Astana/u';

    /**
     * Правки мусора от прошлых автозамен: «Астанаа (Астаны)»,
