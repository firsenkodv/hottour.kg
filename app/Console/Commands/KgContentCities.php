     */
    private const PRE_CLEAN = [
        ['/Астан[а-яё]*\s*\((Астан[а-яё]*)\)/u', '$1'],
        ['/Астанаа/u', 'Астаны'],
        // опечатки «Алмата», «Алмате» приводим к нормальной форме
        ['/(?<![А-Яа-яЁё])Алмат[ае](?![а-яё])/u', 'Алматы'],
    ];

    /**
     * Порядок важен: частные правила раньше общих, предложные пары
